"""
Full metasurface beam steering simulation.

Loads the phase library from unit_cell_sweep.py, computes the required
phase gradient for the target steering angle, assigns pillar widths,
and runs a 2D FDTD simulation of the full supercell.

Usage
-----
    python run.py 01_beam_steering/full_array_sim.py [options]

    or edit the USER PARAMETERS block below and run directly.

Requires
--------
    results/phase_library.npz  (generated by unit_cell_sweep.py)

Output
------
    results/pillar_layout.png          geometry visualisation
    results/epsilon_map.png            MEEP permittivity map
    results/farfield_<angle>deg.png    angular spectrum
    results/farfield_<angle>deg.npz    raw farfield data
    stdout: summary table with steering efficiency
"""

